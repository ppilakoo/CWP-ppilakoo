#!/usr/bin/env python3

stnum = int(input("Give me the first number: ").strip())
ndnum = int(input("Give me the second number: ").strip())
print("Thank you!")
print(f"{stnum} + {ndnum} = {stnum+ndnum}")
print(f"{stnum} - {ndnum} = {stnum-ndnum}")
print(f"{stnum} / {ndnum} = {stnum//ndnum}")
print(f"{stnum} * {ndnum} = {stnum*ndnum}")